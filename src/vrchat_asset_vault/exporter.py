"""Clean export to Unity.

Copies the model + its neighbouring textures into Export_<World>/,
writes manifest.json with origin/license per file, and warns instead
of silently dropping a missing texture or a bad FBX.

Rules enforced here (from VRCLibrary / BKeeper guides):
- Never hand Unity a .blend directly — export FBX first.
- An OBJ without its .mtl gets a warning: no material will be assigned.
- FBX must be binary, version 7.1 or newer, or Unity may refuse it.

Two export shapes:
- a folder (export_collection): models + textures + manifest.json +
  CREDITS.md, ready to drag into a Unity project.
- a .unitypackage (export_unitypackage): the same files as a single
  tar.gz Unity opens on double-click, each file with a stable .meta
  GUID derived from its content hash.
"""
from __future__ import annotations

import hashlib
import io
import json
import shutil
import struct
import tarfile
from pathlib import Path

from .budget import scale_warning
from .scanner import find_textures_for, fbx_unit_scale_factor


def is_binary_fbx(path: Path) -> bool:
    with path.open("rb") as f:
        return f.read(23).startswith(b"Kaydara FBX Binary")


def fbx_version(path: Path) -> int | None:
    """Binary FBX version (e.g. 7400 = 7.4), or None if not binary FBX."""
    try:
        with path.open("rb") as f:
            head = f.read(27)
    except OSError:
        return None
    if not head.startswith(b"Kaydara FBX Binary"):
        return None
    if len(head) < 27:
        return None
    return struct.unpack("<I", head[23:27])[0]


def _guid_for(path: Path) -> str:
    """Stable 32-hex GUID for a file, derived from its content hash."""
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()[:32]


def _meta_text(guid: str) -> str:
    return (
        "fileFormatVersion: 2\n"
        f"guid: {guid}\n"
        "DefaultImporter:\n"
        "  userData: \n"
        "  assetBundleName: \n"
        "  assetBundleVariant: \n"
    )


def write_credits(model_paths: list[Path], meta_by_path: dict, out_path: Path) -> None:
    """CREDITS.md: who made each asset and under what license.

    Losing the origin of a model is how creators end up using a
    Booth/Gumroad asset in a way its license forbids — the credits
    travel with every export so the answer is always one file away.
    """
    lines = [
        "# Credits\n",
        "Generated by VRChat Asset Vault. Check each license before "
        "redistributing, reselling, or using an asset commercially — "
        "most store licenses (Booth, Gumroad) forbid redistribution "
        "of the raw files.\n",
    ]
    for model in model_paths:
        m = meta_by_path.get(str(model), {}) or {}
        lines.append(f"## {model.name}\n")
        for label, key in (
            ("Source", "source"),
            ("Author", "author"),
            ("URL", "url"),
            ("License", "license"),
            ("Tags", "tags"),
        ):
            value = (m.get(key) or "").strip()
            if value:
                lines.append(f"- **{label}:** {value}\n")
        if not any((m.get(k) or "").strip() for k in ("source", "author", "url", "license")):
            lines.append("- **Origin:** unknown — fill it in before sharing this export.\n")
        lines.append("\n")
    out_path.write_text("".join(lines), encoding="utf-8")


def _collect_files(model: Path) -> list[Path]:
    """A model plus the files Unity needs with it (textures, .mtl)."""
    files = [model]
    if model.suffix.lower() == ".obj":
        mtl = model.with_suffix(".mtl")
        if mtl.exists():
            files.append(mtl)
    files.extend(find_textures_for(model))
    return files


def _check_model(model: Path, warnings: list[str]) -> None:
    if model.suffix.lower() == ".blend":
        warnings.append(
            f"{model.name}: .blend files must be exported as FBX before Unity — copied as-is, do not import directly."
        )
    if model.suffix.lower() == ".fbx":
        if not is_binary_fbx(model):
            warnings.append(
                f"{model.name}: FBX is not binary — Unity needs binary FBX 7.1+."
            )
        else:
            version = fbx_version(model)
            if version is not None and version < 7100:
                major, minor = version // 1000, (version % 1000) // 100
                warnings.append(
                    f"{model.name}: FBX version {major}.{minor} "
                    "— Unity needs binary FBX 7.1+."
                )
            scale = scale_warning(fbx_unit_scale_factor(model))
            if scale is not None:
                warnings.append(f"{model.name}: {scale}")
    if model.suffix.lower() == ".obj":
        if not model.with_suffix(".mtl").exists():
            warnings.append(
                f"{model.name}: no .mtl found — Unity will assign no material."
            )


def export_collection(
    model_paths: list[Path],
    out_dir: Path,
    world_name: str,
    meta_by_path: dict | None = None,
) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest: list[dict] = []
    warnings: list[str] = []
    meta_by_path = meta_by_path or {}

    for model in model_paths:
        dest = out_dir / model.name
        shutil.copy2(model, dest)
        entry: dict = {"file": model.name, "source_path": str(model)}
        _check_model(model, warnings)
        if model.suffix.lower() == ".obj":
            mtl = model.with_suffix(".mtl")
            if mtl.exists():
                shutil.copy2(mtl, out_dir / mtl.name)
                entry["mtl"] = mtl.name
        textures = find_textures_for(model)
        entry["textures"] = []
        for tex in textures:
            shutil.copy2(tex, out_dir / tex.name)
            entry["textures"].append(tex.name)
        if not textures:
            warnings.append(f"{model.name}: no textures found next to the model.")
        m = meta_by_path.get(str(model), {}) or {}
        for key in ("source", "author", "url", "license", "tags"):
            entry[key] = m.get(key, "")
        manifest.append(entry)

    (out_dir / "manifest.json").write_text(
        json.dumps({"world": world_name, "assets": manifest}, indent=2),
        encoding="utf-8",
    )
    if meta_by_path:
        write_credits(model_paths, meta_by_path, out_dir / "CREDITS.md")
    return {"out_dir": str(out_dir), "assets": len(manifest), "warnings": warnings}


def export_unitypackage(
    model_paths: list[Path],
    out_file: Path,
    world_name: str,
    meta_by_path: dict | None = None,
) -> dict:
    """Write a .unitypackage (tar.gz) Unity opens on double-click."""
    meta_by_path = meta_by_path or {}
    warnings: list[str] = []
    out_file.parent.mkdir(parents=True, exist_ok=True)
    credits: io.BytesIO | None = None
    if meta_by_path:
        tmp = out_file.with_suffix(".credits.md")
        write_credits(model_paths, meta_by_path, tmp)
        credits = io.BytesIO(tmp.read_bytes())
        tmp.unlink()
    with tarfile.open(out_file, "w:gz") as tar:
        seen: set[str] = set()

        def _add(name: str, data: bytes) -> None:
            if name in seen:
                return
            seen.add(name)
            info = tarfile.TarInfo(name)
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))

        for model in model_paths:
            _check_model(model, warnings)
            for src in _collect_files(model):
                _add(f"Assets/{src.name}", src.read_bytes())
                _add(
                    f"Assets/{src.name}.meta",
                    _meta_text(_guid_for(src)).encode("utf-8"),
                )
            if not find_textures_for(model):
                warnings.append(f"{model.name}: no textures found next to the model.")
        if credits is not None:
            data = credits.getvalue()
            _add("Assets/CREDITS.md", data)
            _add(
                "Assets/CREDITS.md.meta",
                _meta_text(hashlib.sha256(data).hexdigest()[:32]).encode("utf-8"),
            )
    return {"out_file": str(out_file), "assets": len(model_paths), "warnings": warnings}
